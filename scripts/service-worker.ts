/**
 * Generates the offline service worker (dist/sw.js) at build time — see the Vite plugin in vite.config.ts.
 * Strategy: precache every built file; serve from cache first, so the app works with no signal.
 * A new version installs in the background and waits; the page offers "Update" (SKIP_WAITING) to switch.
 */
import { createHash } from "node:crypto";

/** Built files (relative to the site root) → URLs to precache, relative to the worker's scope. */
export const precacheList = (files: readonly string[]): string[] => {
  const urls = files.filter((f) => !f.endsWith(".map") && f !== "sw.js").map((f) => `./${f}`);
  return [...new Set(["./", ...urls])].sort();
};

const WORKER_BODY = `
const SHELL = "./index.html";

self.addEventListener("install", (event) => {
  event.waitUntil(caches.open(CACHE).then((cache) => cache.addAll(PRECACHE)));
});

self.addEventListener("activate", (event) => {
  event.waitUntil(
    caches.keys()
      .then((keys) => Promise.all(keys.filter((k) => k.startsWith("biochem-") && k !== CACHE).map((k) => caches.delete(k))))
      .then(() => self.clients.claim()),
  );
});

self.addEventListener("message", (event) => {
  if (event.data && event.data.type === "SKIP_WAITING") self.skipWaiting();
});

self.addEventListener("fetch", (event) => {
  const request = event.request;
  if (request.method !== "GET") return;
  const url = new URL(request.url);
  if (url.origin !== self.location.origin) return;
  const lookup = request.mode === "navigate" ? caches.match(SHELL) : caches.match(request);
  event.respondWith(lookup.then((cached) => cached || fetch(request)));
});
`;

/** `fingerprint` should cover file contents (the build passes them), so any content change ships a new cache. */
export const buildServiceWorker = (precache: readonly string[], fingerprint: string = precache.join("\n")): string => {
  const version = createHash("sha256").update(fingerprint).digest("hex").slice(0, 12);
  return `/* Generated by scripts/service-worker.ts — do not edit. */\n"use strict";\nconst CACHE = "biochem-${version}";\nconst PRECACHE = ${JSON.stringify(precache)};\n${WORKER_BODY}`;
};
